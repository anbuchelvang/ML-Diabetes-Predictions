import os
import json
import joblib
import numpy as np

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ML_DIR = os.path.join(BASE_DIR, "ml")
BACKEND_SERVICES_DIR = os.path.join(BASE_DIR, "backend", "services")

FEATURE_NAMES = [
    "Pregnancies", "Glucose", "BloodPressure", "SkinThickness",
    "Insulin", "BMI", "DiabetesPedigreeFunction", "Age"
]

class DiabetesPredictor:
    def __init__(self, model_path=None, scaler_path=None, metrics_path=None):
        # Determine locations (prefer backend/services if available, fallback to ml/)
        if not model_path:
            model_path = os.path.join(BACKEND_SERVICES_DIR, "model.pkl")
            if not os.path.exists(model_path):
                model_path = os.path.join(ML_DIR, "model.pkl")

        if not scaler_path:
            scaler_path = os.path.join(BACKEND_SERVICES_DIR, "scaler.pkl")
            if not os.path.exists(scaler_path):
                scaler_path = os.path.join(ML_DIR, "scaler.pkl")

        if not metrics_path:
            metrics_path = os.path.join(BACKEND_SERVICES_DIR, "metrics.json")
            if not os.path.exists(metrics_path):
                metrics_path = os.path.join(ML_DIR, "metrics.json")

        if not os.path.exists(model_path) or not os.path.exists(scaler_path):
            raise FileNotFoundError("Trained model or scaler not found. Run train_model.py first.")

        self.model = joblib.load(model_path)
        self.scaler = joblib.load(scaler_path)
        
        with open(metrics_path, "r") as f:
            self.metrics_info = json.load(f)
            
        self.medians = self.metrics_info.get("feature_medians", {})
        self.feature_importances = self.metrics_info.get("feature_importances", {})

    def predict(self, input_data: dict) -> dict:
        """
        Takes raw dictionary of input health parameters, performs scaling, 
        prediction, probability calculation, and local XAI impact breakdown.
        """
        # Parse inputs & impute zero biological metrics
        processed_values = []
        zero_impute_cols = ["Glucose", "BloodPressure", "SkinThickness", "Insulin", "BMI"]

        for col in FEATURE_NAMES:
            val = float(input_data.get(col, 0))
            if col in zero_impute_cols and val <= 0:
                val = float(self.medians.get(col, 100))
            processed_values.append(val)

        X_raw = np.array([processed_values])
        X_scaled = self.scaler.transform(X_raw)

        # Raw Model Outcome & Probability
        raw_pred = int(self.model.predict(X_scaled)[0])
        probabilities = self.model.predict_proba(X_scaled)[0]
        pos_prob = float(probabilities[1])
        prob_percentage = round(pos_prob * 100, 1)

        # Risk Classification Level
        if pos_prob >= 0.65:
            risk_level = "High Risk"
            risk_color = "red"
        elif pos_prob >= 0.40:
            risk_level = "Moderate Risk"
            risk_color = "amber"
        else:
            risk_level = "Low Risk"
            risk_color = "emerald"

        # Calculate Explainable AI (XAI) Feature Contribution
        xai_breakdown = self._compute_feature_contributions(X_raw[0], X_scaled[0], pos_prob)

        # Personalized Health Guidance
        guidance = self._generate_guidance(input_data, risk_level, pos_prob)

        return {
            "prediction": raw_pred,
            "risk_level": risk_level,
            "risk_color": risk_color,
            "probability_percentage": prob_percentage,
            "raw_probability": round(pos_prob, 4),
            "feature_contributions": xai_breakdown,
            "guidance": guidance,
            "disclaimer": "This prediction is generated by a Machine Learning model for educational and risk-screening purposes only. It does NOT constitute a clinical medical diagnosis. Please consult a qualified physician or endocrinologist."
        }

    def _compute_feature_contributions(self, raw_features, scaled_features, pos_prob):
        """
        Computes normalized local impact for each feature based on feature weights 
        and scaled distance from the dataset population mean.
        """
        contributions = []

        # Mean and Scale from Scaler
        means = self.scaler.mean_
        scales = self.scaler.scale_

        for i, col in enumerate(FEATURE_NAMES):
            global_weight = self.feature_importances.get(col, 0.125)
            scaled_val = scaled_features[i]
            
            # Local impact is proportional to scaled distance * global feature importance
            impact_score = float(global_weight * scaled_val)
            abs_impact = abs(impact_score)

            if abs_impact > 0.4:
                impact_label = "High Impact"
            elif abs_impact > 0.15:
                impact_label = "Medium Impact"
            else:
                impact_label = "Low Impact"

            direction = "Increasing Risk" if impact_score > 0 else "Lowering Risk"

            contributions.append({
                "feature": col,
                "user_value": round(float(raw_features[i]), 2),
                "global_importance": round(global_weight, 4),
                "impact_score": round(impact_score, 4),
                "abs_impact": round(abs_impact, 4),
                "impact_label": impact_label,
                "direction": direction
            })

        # Sort contributions by absolute impact descending
        contributions.sort(key=lambda x: x["abs_impact"], reverse=True)

        # Calculate relative impact percentage for bar chart visual
        total_abs = sum(c["abs_impact"] for c in contributions) or 1.0
        for c in contributions:
            c["relative_percentage"] = round((c["abs_impact"] / total_abs) * 100, 1)

        return contributions

    def _generate_guidance(self, data, risk_level, prob):
        glucose = float(data.get("Glucose", 0))
        bmi = float(data.get("BMI", 0))
        age = float(data.get("Age", 0))
        bp = float(data.get("BloodPressure", 0))

        tips = []

        if glucose >= 140:
            tips.append("Your blood glucose level is elevated (>140 mg/dL). Consider scheduling a Fasting Plasma Glucose or HbA1c test with your primary care provider.")
        elif glucose >= 100:
            tips.append("Your blood glucose is in the prediabetes risk range (100-139 mg/dL). Reducing refined sugar and simple carbohydrates can help normalize levels.")

        if bmi >= 30:
            tips.append("Your BMI indicates obesity (>=30). A structured weight management program incorporating 150 minutes/week of aerobic exercise can reduce diabetes risk by up to 58%.")
        elif bmi >= 25:
            tips.append("Your BMI is in the overweight range (25-29.9). Modest weight loss of 5-7% of total body weight produces significant metabolic benefits.")

        if bp >= 90:
            tips.append("Elevated diastolic blood pressure (>=90 mmHg) noticed. Regular cardiovascular exercise and salt reduction are beneficial.")

        if not tips:
            tips.append("Maintain a balanced diet rich in dietary fiber, whole grains, and lean proteins while exercising regularly.")

        summary_message = (
            f"Based on your health metrics, your calculated diabetes risk score is {risk_level} ({round(prob*100, 1)}%). "
            "Primary contributing metrics have been highlighted above."
        )

        return {
            "summary": summary_message,
            "recommendations": tips
        }

